export type IconName = keyof typeof ICONS;

const cache = new Map<string, string>();

/** An icon as SVG markup: one path of 1x1 squares, merged along each row. */
export function iconSvg(name: string): string {
  const hit = cache.get(name);
  if (hit) return hit;
  const rows = ICONS[name as IconName];
  if (!rows) return "";
  let d = "";
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== "#") continue;
      let w = 1;
      while (row[x + w] === "#") w++;
      d += `M${x} ${y}h${w}v1h-${w}z`;
      x += w - 1;
    }
  });
  const size = rows.length;
  const svg = `<svg class="icon" viewBox="0 0 ${size} ${size}" shape-rendering="crispEdges" aria-hidden="true"><path fill="currentColor" d="${d}"/></svg>`;
  cache.set(name, svg);
  return svg;
}

/** An icon as an element, ready to put in front of a label. */
export function iconEl(name: string): HTMLElement {
  const span = document.createElement("span");
  span.className = "ic";
  span.innerHTML = iconSvg(name);
  return span;
}

